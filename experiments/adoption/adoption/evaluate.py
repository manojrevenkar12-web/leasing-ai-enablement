"""Run the simulated rollout, analyse it, and score every estimator against the truth.

Writes reports/adoption/results.json and reports/adoption/RESULTS.md (generated; do not edit).
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

from adoption import analysis, sim

ROOT = Path(__file__).resolve().parents[1]
REPO = ROOT.parents[1]


def truth(effects: pd.DataFrame, gt_cells: pd.DataFrame | None = None) -> dict[str, float]:
    """True average effect over treated team-weeks, the same cells the estimators average over."""
    treated = effects[effects["adopt_week"].notna() & (effects["week"] >= effects["adopt_week"])]
    return {
        "throughput": float(treated["throughput_effect"].mean()),
        "rework": float(treated["rework_effect"].mean()),
        "cycle_time": float(treated["cycle_time_effect"].mean()),
    }


def truth_by_event_time(effects: pd.DataFrame, column: str, max_e: int = 11) -> dict[int, float]:
    t = effects[effects["adopt_week"].notna() & (effects["week"] >= effects["adopt_week"])].copy()
    t["e"] = (t["week"] - t["adopt_week"]).astype(int)
    return {int(e): float(v) for e, v in t[t["e"] <= max_e].groupby("e")[column].mean().items()}


def run(data: Path = ROOT / "data", reps: int = 200) -> dict:
    cfg = json.loads((ROOT / "config.json").read_text())
    sim.main(data)
    p = analysis.load(data, cfg["weeks"])
    effects = pd.read_csv(data / "truth/effects.csv")
    true = truth(effects)

    results: dict = {"truth": true, "estimates": {}, "intervals": {}, "event_study": {}}
    for y in analysis.OUTCOMES:
        results["estimates"][y] = {name: est(p, y).relative for name, est in analysis.ESTIMATORS.items()}
        results["intervals"][y] = analysis.bootstrap(p, y, reps, cfg["seed"])
        es = analysis.event_study(p, y)
        col = {"throughput": "throughput_effect", "rework": "rework_effect", "cycle_time": "cycle_time_effect"}[y]
        tes = truth_by_event_time(effects, col)
        results["event_study"][y] = [{"e": int(r.e), "estimate": float(r.relative), "truth": tes.get(int(r.e))} for r in es.itertuples()]
    # The decision the playbook needs: did rework come down once the paved road was in place?
    enable = json.loads((ROOT / "world.json").read_text())["true_effects"]["enablement_after_weeks"]
    rows = results["event_study"]["rework"]
    phase = lambda early: [r for r in rows if (r["e"] < enable) == early]  # noqa: E731
    results["rework_phases"] = {
        name: {"estimate": float(np.mean([r["estimate"] for r in phase(early)])), "truth": float(np.mean([r["truth"] for r in phase(early)]))}
        for name, early in (("first weeks", True), ("after the paved road", False))
    }
    results["errors"] = {
        y: {name: abs(v - true[y]) for name, v in results["estimates"][y].items()} for y in analysis.OUTCOMES
    }
    results["teams"] = int(p["team"].nunique())
    results["pull_requests"] = int(p["prs"].sum())
    return results


def markdown(r: dict) -> str:
    pct = lambda v: f"{v * 100:+.1f}%"  # noqa: E731
    names = {"before_after": "Before vs after (adopters)", "adopters_vs_rest": "Adopters vs never-adopters", "twfe": "Two-way fixed effects", "callaway_santanna": "Callaway–Sant'Anna (shipped)"}
    lines = [
        "# AI-tool rollout: what each way of measuring says",
        "",
        "Generated by `python -m adoption.evaluate`. Do not edit.",
        "",
        f"{r['teams']} teams, {r['pull_requests']:,} pull requests. The truth is known because the organisation is simulated; the estimators only see pull requests and rollout dates.",
        "",
        "| Estimator | Throughput | Rework | Cycle time |",
        "| --- | --- | --- | --- |",
        f"| **Truth** | **{pct(r['truth']['throughput'])}** | **{pct(r['truth']['rework'])}** | **{pct(r['truth']['cycle_time'])}** |",
    ]
    for k, label in names.items():
        lines.append(f"| {label} | {pct(r['estimates']['throughput'][k])} | {pct(r['estimates']['rework'][k])} | {pct(r['estimates']['cycle_time'][k])} |")
    ci = r["intervals"]
    lines += [
        f"| 95% interval (Callaway–Sant'Anna, teams resampled) | {pct(ci['throughput'][0])} to {pct(ci['throughput'][1])} | {pct(ci['rework'][0])} to {pct(ci['rework'][1])} | {pct(ci['cycle_time'][0])} to {pct(ci['cycle_time'][1])} |",
        "",
        "## Rework: before and after the paved road (review guardrails, conventions, hooks)",
        "",
        "| Phase | Estimate (Callaway–Sant'Anna) | Truth |",
        "| --- | --- | --- |",
        *[f"| {k} | {pct(v['estimate'])} | {pct(v['truth'])} |" for k, v in r["rework_phases"].items()],
        "",
        "## Rework by weeks since a team adopted",
        "",
        "| Week | Estimate | Truth |",
        "| --- | --- | --- |",
    ]
    for row in r["event_study"]["rework"]:
        lines.append(f"| {row['e']} | {pct(row['estimate'])} | {pct(row['truth']) if row['truth'] is not None else '–'} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    r = run()
    out = REPO / "reports/adoption"
    out.mkdir(parents=True, exist_ok=True)
    (out / "results.json").write_text(json.dumps(r, indent=2, default=lambda o: float(o) if isinstance(o, np.floating) else str(o)) + "\n")
    (out / "RESULTS.md").write_text(markdown(r))
    print(markdown(r))


if __name__ == "__main__":
    main()
